#!/usr/bin/env node
/**
 * Generate dsh-agent-teams named-profile config from the canonical role
 * definitions in `agents/roles/*.md` plus a squad/routing declaration
 * (`teams.routing.json`).
 *
 * Single source of truth: the role markdown bodies are emitted verbatim as
 * `members[].role` persona text (the same text the liangshen-roles preset
 * embeds for tool-style dispatch). The only synthesized text is the preamble,
 * which reframes the tool-dispatch Input Packet convention for persistent
 * team members (assignment message + task contract instead of a dispatch
 * prompt; Output Packet delivered via `agent_teams_update_task`).
 *
 * Usage:
 *   node scripts/agent-teams-profiles/gen.mjs                 # fragment to stdout
 *   node scripts/agent-teams-profiles/gen.mjs --out <file>    # fragment to file
 *
 * The output is a `cordis.patch.yml` fragment (id-targeted config override on
 * the `agent-teams` plugin row) wrapped in BEGIN/END markers so it can be
 * spliced and later regenerated idempotently.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..', '..')

const args = process.argv.slice(2)
function argValue(flag) {
  const i = args.indexOf(flag)
  return i >= 0 ? args[i + 1] : undefined
}
const outPath = argValue('--out')
const rolesDir = resolve(argValue('--roles') ?? join(repoRoot, 'agents', 'roles'))
const routingPath = resolve(argValue('--routing') ?? join(scriptDir, 'teams.routing.json'))

const routing = JSON.parse(readFileSync(routingPath, 'utf8'))
const PERSONA_PROTOCOL_MAX_CHARS = 400 // mirror of dsh-agent-teams members.ts

function roleBody(role) {
  const raw = readFileSync(join(rolesDir, `${role}.md`), 'utf8')
  const parts = raw.split(/^---\s*$/m)
  if (parts.length < 3) throw new Error(`role "${role}": frontmatter not found`)
  // body after the closing '---': drop the H1 title? The proven preset text
  // keeps it — keep the body verbatim, only trim leading/final blank lines.
  const body = parts.slice(2).join('---').replace(/^\s*\n/, '').replace(/\s+$/, '')
  if (!body.trim()) throw new Error(`role "${role}": empty body`)
  return body
}

function blockScalar(text, indent) {
  const pad = ' '.repeat(indent)
  const lines = text.split('\n').map((l) => (l.trim() === '' ? '' : pad + l.replace(/\s+$/, '')))
  return '|-\n' + lines.join('\n')
}

function main() {
  const plugin = routing.plugin ?? {}
  const maxMembers = plugin.maxMembers ?? 8
  const provider = routing.provider
  if (!provider) throw new Error('routing.provider is required')
  const preamble = routing.preambleTemplate ?? ''
  if (!preamble.includes('{role}')) throw new Error('preambleTemplate must contain {role}')

  const errors = []
  const squadNames = Object.keys(routing.squads ?? {})
  if (squadNames.length === 0) throw new Error('no squads declared')

  const renderedSquads = squadNames.map((squad) => {
    const def = routing.squads[squad]
    if (!Array.isArray(def.members) || def.members.length === 0) {
      throw new Error(`squad "${squad}" has no members`)
    }
    if (def.members.length > maxMembers) {
      throw new Error(`squad "${squad}" has ${def.members.length} members > maxMembers ${maxMembers}`)
    }
    if (def.protocol && def.protocol.length > PERSONA_PROTOCOL_MAX_CHARS) {
      throw new Error(
        `squad "${squad}" protocol is ${def.protocol.length} chars > ${PERSONA_PROTOCOL_MAX_CHARS} (would be truncated in member personas)`,
      )
    }
    const members = def.members.map((m) => {
      if (!m.role || !m.model) errors.push(`squad "${squad}": member needs role+model (provider/model must be a pair)`)
      if (m.role === 'captain') errors.push(`squad "${squad}": "captain" is a reserved member name`)
      const persona = preamble.replaceAll('{role}', m.role) + '\n\n' + roleBody(m.role)
      return { name: m.role, model: m.model, executionPrompt: m.executionPrompt, persona }
    })
    if (errors.length > 0) throw new Error(errors.join('; '))
    return { squad, def, members }
  })

  const L = []
  L.push('# BEGIN agent-teams-profiles (generated by scripts/agent-teams-profiles/gen.mjs — edit teams.routing.json or agents/roles/*.md, then regenerate; do not edit by hand)')
  L.push('- id: agent-teams')
  L.push('  config:')
  if (plugin.memberMaxDepth !== undefined) L.push(`    memberMaxDepth: ${plugin.memberMaxDepth}`)
  if (plugin.maxMembers !== undefined) L.push(`    maxMembers: ${plugin.maxMembers}`)
  if (plugin.stateDir) L.push(`    stateDir: ${plugin.stateDir}`)
  if (plugin.memberProvider) L.push(`    memberProvider: ${plugin.memberProvider}`)
  L.push('    profiles:')
  for (const { squad, def, members } of renderedSquads) {
    L.push(`      ${squad}:`)
    if (def.description) L.push(`        description: ${JSON.stringify(def.description)}`)
    if (def.protocol) L.push('        protocol: ' + JSON.stringify(def.protocol))
    L.push('        taskPlanning: captain')
    L.push('        members:')
    for (const m of members) {
      L.push(`          - name: ${m.name}`)
      L.push(`            provider: ${provider}`)
      L.push(`            model: ${m.model}`)
      if (m.executionPrompt) L.push('            executionPrompt: ' + JSON.stringify(m.executionPrompt))
      L.push('            role: ' + blockScalar(m.persona, 14))
    }
  }
  L.push('# END agent-teams-profiles')
  const out = L.join('\n') + '\n'

  if (outPath) {
    writeFileSync(outPath, out)
    console.error(`wrote ${outPath} (${out.split('\n').length} lines)`)
  } else {
    process.stdout.write(out)
  }
}

try {
  main()
} catch (err) {
  console.error(`gen-teams-profiles: ${err.message}`)
  process.exit(1)
}
